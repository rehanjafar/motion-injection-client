import Foundation

@main struct JourneyChecks {
    static func main() {
        var checks = 0
        func check(_ condition: @autoclosure () -> Bool, _ message: String) { checks += 1; precondition(condition(),message) }
        let a = GeoPoint(latitude:0,longitude:0)
        let b = GeoPoint(latitude:0,longitude:0.001)
        let c = GeoPoint(latitude:0,longitude:0.002)
        check(abs(a.distance(to:b)-111.195)<0.01,"Great-circle distance")
        check(!GeoPoint(latitude:.nan,longitude:0).isValid,"Reject nonfinite coordinates")
        check(!GeoPoint(latitude:91,longitude:0).isValid,"Reject out-of-range latitude")
        let crossing = GeoPoint(latitude:0,longitude:179).interpolated(to:.init(latitude:0,longitude:-179),fraction:0.5)
        check(abs(crossing.longitude)==180,"Dateline crosses the short way")
        let stops = [JourneyStop(name:"A",point:a,waitSeconds:2,departureSpeed:36),JourneyStop(name:"B",point:b,waitSeconds:3,departureSpeed:72),JourneyStop(name:"C",point:c)]
        let plan = JourneyPlan(stops:stops,legs:[JourneyLeg(points:[a,b]),JourneyLeg(points:[b,c])],mode:"Car")
        check(plan.isValid,"Valid route")
        var cursor = JourneyCursor(plan:plan,speed:5)
        check(cursor.speed==36,"First stop overrides initial speed")
        cursor.advance(seconds:1)
        check(cursor.point==a && cursor.waiting==1,"Wait at first stop")
        cursor.advance(seconds:2)
        check(abs(cursor.meters-10)<0.01,"Move only after wait")
        cursor.advance(seconds:(plan.legs[0].distance-10)/10)
        check(cursor.legIndex==1 && cursor.waiting==3 && cursor.speed==72,"Intermediate wait and departure speed")
        cursor.advance(seconds:2)
        check(cursor.point==b && cursor.waiting==1,"Intermediate stop holds")
        cursor.advance(seconds:2)
        check(abs(cursor.meters-20)<0.01,"New speed after wait")
        cursor.advance(seconds:100)
        check(cursor.finished && cursor.point==c,"Hold final destination")
        let last = cursor.point; cursor.advance(seconds:100)
        check(cursor.point==last,"Finished journey remains fixed")
        var bad = plan; bad.stops[0].departureSpeed = 200
        check(!bad.isValid,"Reject excessive speed")
        bad = plan; bad.stops[0].waitSeconds = -1
        check(!bad.isValid,"Reject negative wait")
        bad = plan; bad.legs = []
        check(!bad.isValid,"Reject missing geometry")
        let zero = JourneyPlan(stops:[JourneyStop(name:"A",point:a),JourneyStop(name:"A",point:a)],legs:[JourneyLeg(points:[a,a])],mode:"Walking")
        var zeroCursor = JourneyCursor(plan:zero,speed:5); zeroCursor.advance(seconds:1)
        check(zeroCursor.finished,"Zero-distance route terminates")
        var live = JourneyCursor(plan:plan,speed:5)
        var proposed = live; proposed.advance(seconds:5)
        check(live.point==a,"Unacknowledged progress does not mutate live cursor")
        live = proposed
        check(live.point != a,"Acknowledged progress can be committed")
        check(BackgroundExecutionPolicy.mayTick(foreground:true,locationActive:false),"Foreground works without background authorization")
        check(BackgroundExecutionPolicy.mayTick(foreground:false,locationActive:true),"Authorized active background session continues")
        check(!BackgroundExecutionPolicy.mayTick(foreground:false,locationActive:false),"Background without active authorization stops")
        check(!BackgroundExecutionPolicy.interrupted(elapsed:1.2),"Ordinary app-switch interval continues")
        check(BackgroundExecutionPolicy.interrupted(elapsed:15),"Actual suspension pauses route")
        check(BackgroundExecutionPolicy.interrupted(elapsed: -1),"Clock rollback does not reverse travel")
        check(BackgroundExecutionPolicy.interrupted(elapsed: .nan),"Nonfinite elapsed time is rejected")

        let date = Date(timeIntervalSince1970:1000)
        let first = ScheduledJourney(name:"Morning",plan:plan,departure:date,speed:5)
        let second = ScheduledJourney(name:"Later",plan:plan,departure:first.arrival,speed:5)
        check(!first.overlaps(second),"Adjacent departures do not overlap")
        var overlapping = second; overlapping.departure = first.arrival.addingTimeInterval(-1)
        check(first.overlaps(overlapping),"Overlapping routes rejected")
        check(abs(first.duration - (2 + plan.legs[0].distance/10 + 3 + plan.legs[1].distance/20)) < 0.001,"Schedule duration includes waits and speed changes")
        let roundtrip = try! JSONDecoder().decode([ScheduledJourney].self,from:JSONEncoder().encode([first,second]))
        check(roundtrip.count == 2 && roundtrip[0].id == first.id && roundtrip[1].plan.isValid,"Multiple route snapshots survive persistence")
        check(DeparturePolicy.decision(departure:date,now:date,armed:true,occupied:false,connected:true) == .start,"Armed departure can start without foreground requirement")
        check(DeparturePolicy.decision(departure:date,now:date,armed:false,occupied:false,connected:true) == .wait,"Unarmed schedules never execute")
        check(DeparturePolicy.decision(departure:date,now:date,armed:true,occupied:true,connected:true) == .wait,"Active route is never overwritten")
        check(DeparturePolicy.decision(departure:date,now:date.addingTimeInterval(61),armed:true,occupied:false,connected:true) == .missed,"Missed route never replays after suspension")
        check(DeparturePolicy.decision(departure:date,now:date.addingTimeInterval(-1),armed:true,occupied:false,connected:true) == .wait,"Future departure cannot start early")
        check(DeparturePolicy.decision(departure:date,now:date,armed:true,occupied:false,connected:false) == .wait,"Disconnected departure waits within grace period")

        let iso = ISO8601DateFormatter()
        func instant(_ value: String) -> Date { iso.date(from:value)! }
        let tuesday = instant("2026-11-03T14:00:00Z") // 09:00 Toronto
        let thursday = instant("2026-11-05T14:00:00Z")
        let rule = WeeklyRepeat(weekdays:[3,5],hour:9,minute:0,timeZoneID:"America/Toronto")
        check(rule.next(after:tuesday) == thursday,"Tuesday/Thursday advances to Thursday")
        check(rule.next(after:thursday) == instant("2026-11-10T14:00:00Z"),"Thursday wraps to next Tuesday")
        check(rule.next(after:tuesday.addingTimeInterval(-1)) == tuesday,"First chosen day is included")
        let mwf = WeeklyRepeat(weekdays:[2,4,6],hour:9,minute:0,timeZoneID:"America/Toronto")
        check(mwf.next(after:tuesday) == instant("2026-11-04T14:00:00Z"),"Monday/Wednesday/Friday selects Wednesday")
        let sunday = WeeklyRepeat(weekdays:[1],hour:9,minute:0,timeZoneID:"America/Toronto")
        check(sunday.next(after:instant("2027-03-07T14:00:00Z")) == instant("2027-03-14T13:00:00Z"),"DST preserves local 09:00 rather than adding 168 hours")
        let skippedHour = WeeklyRepeat(weekdays:[1],hour:2,minute:30,timeZoneID:"America/Toronto")
        check(skippedHour.next(after:instant("2027-03-14T05:00:00Z")) == instant("2027-03-14T07:00:00Z"),"Spring clock gap uses next valid time")
        let repeatedHour = WeeklyRepeat(weekdays:[1],hour:1,minute:30,timeZoneID:"America/Toronto")
        let fall = repeatedHour.next(after:instant("2026-11-01T04:00:00Z"))!
        check(fall == instant("2026-11-01T05:30:00Z"),"Fall repeated hour chooses first occurrence")
        check(repeatedHour.next(after:fall) == instant("2026-11-08T06:30:00Z"),"Fall repeated hour does not run twice")
        check(!WeeklyRepeat(weekdays:[],hour:9,minute:0,timeZoneID:"America/Toronto").isValid,"Empty repeat rejected")
        check(!WeeklyRepeat(weekdays:[8],hour:9,minute:0,timeZoneID:"America/Toronto").isValid,"Invalid weekday rejected")
        var recurring = ScheduledJourney(name:"Campus",plan:plan,departure:tuesday,speed:5,weeklyRepeat:rule)
        var completed = recurring; completed.finishOccurrence("Completed",now:tuesday.addingTimeInterval(30))
        check(completed.departure == thursday && completed.state == "Pending" && completed.lastOutcome == "Completed","Completed occurrence preserves weekly schedule")
        recurring.finishOccurrence("Missed",now:instant("2026-11-20T14:00:00Z"))
        check(recurring.departure == instant("2026-11-24T14:00:00Z"),"Long absence skips missed weeks without replaying")
        var oneOff = first; oneOff.finishOccurrence("Completed",now:first.arrival)
        check(oneOff.state == "Completed" && oneOff.departure == first.departure,"One-time completion stays terminal")
        let recurringOriginal = ScheduledJourney(name:"Campus",plan:plan,departure:tuesday,speed:5,weeklyRepeat:rule)
        let futureConflict = ScheduledJourney(name:"Other",plan:plan,departure:thursday,speed:5)
        check(recurringOriginal.overlaps(futureConflict),"Conflict found on later repeat rather than first departure only")
        let noConflict = ScheduledJourney(name:"Other",plan:plan,departure:thursday.addingTimeInterval(3600),speed:5)
        check(!recurringOriginal.overlaps(noConflict),"Separate departure time remains allowed")
        var longPlan = plan; longPlan.stops[0].waitSeconds = 86400
        let daily = WeeklyRepeat(weekdays:Set(1...7),hour:9,minute:0,timeZoneID:"America/Toronto")
        let selfConflict = ScheduledJourney(name:"Too long",plan:longPlan,departure:tuesday,speed:5,weeklyRepeat:daily)
        check(selfConflict.overlapsOwnRepeat,"A route cannot overlap its own next run")
        let recurringData = try! JSONEncoder().encode(recurringOriginal)
        let restoredRepeat = try! JSONDecoder().decode(ScheduledJourney.self,from:recurringData)
        check(restoredRepeat.weeklyRepeat == rule && restoredRepeat.id == recurringOriginal.id,"Repeat days and timezone survive persistence")
        var legacy = try! JSONSerialization.jsonObject(with:JSONEncoder().encode(first)) as! [String:Any]
        legacy.removeValue(forKey:"weeklyRepeat"); legacy.removeValue(forKey:"lastOutcome")
        let restoredLegacy = try! JSONDecoder().decode(ScheduledJourney.self,from:JSONSerialization.data(withJSONObject:legacy))
        check(restoredLegacy.weeklyRepeat == nil && restoredLegacy.id == first.id,"Existing saved departures decode without migration loss")
        var notice = RouteMovementNotice(name:"Campus")
        check(notice.take(from:a,to:a,acknowledged:true) == nil,"Waiting at first stop sends no movement notification")
        check(notice.take(from:a,to:b,acknowledged:false) == nil,"Failed movement sends no notification")
        check(notice.take(from:a,to:b,acknowledged:true) == "Campus","Acknowledged movement sends route name")
        check(notice.take(from:b,to:c,acknowledged:true) == nil,"Later movement does not duplicate notification")

        var windowed = ScheduledJourney(name:"Random",plan:plan,departure:tuesday,speed:5,weeklyRepeat:rule,
            windowStart:tuesday,windowSeconds:300)
        windowed.chooseDeparture(unit:0)
        check(windowed.departure == tuesday,"Random window can select its lower bound")
        windowed.chooseDeparture(unit:1)
        check(windowed.departure == tuesday.addingTimeInterval(300),"Random window can select its upper bound")
        windowed.chooseDeparture(unit:0.5)
        check(windowed.departure == tuesday.addingTimeInterval(150),"Random time falls between window endpoints")
        check(windowed.isValid,"Valid random window accepted")
        let windowData = try! JSONEncoder().encode(windowed)
        let loadedWindow = try! JSONDecoder().decode(ScheduledJourney.self,from:windowData)
        check(loadedWindow.departure == windowed.departure && loadedWindow.windowStart == tuesday && loadedWindow.windowSeconds == 300,"Saved chosen time survives reopening without rerolling")
        var renamed = loadedWindow; renamed.name = "Renamed"
        check(renamed.id == loadedWindow.id && renamed.departure == loadedWindow.departure,"Metadata edit retains occurrence identity and random time")
        windowed.finishOccurrence("Completed",now:tuesday.addingTimeInterval(600))
        check(windowed.windowStart == thursday && windowed.departure >= thursday && windowed.departure <= thursday.addingTimeInterval(300),"Next weekly occurrence gets a new time inside its own window")
        var invalidWindow = windowed; invalidWindow.windowSeconds = -1
        check(!invalidWindow.isValid,"Negative window rejected")
        invalidWindow = windowed; invalidWindow.windowSeconds = 86401
        check(!invalidWindow.isValid,"Window longer than 24 hours rejected")
        invalidWindow = windowed; invalidWindow.departure = thursday.addingTimeInterval(301)
        check(!invalidWindow.isValid,"Chosen time outside window rejected")
        var oneWindow = ScheduledJourney(name:"Window",plan:plan,departure:tuesday,speed:5,windowStart:tuesday,windowSeconds:300)
        oneWindow.chooseDeparture(unit:0)
        let lateConflict = ScheduledJourney(name:"Conflict",plan:plan,departure:tuesday.addingTimeInterval(299),speed:5)
        check(oneWindow.overlaps(lateConflict),"Whole window reserved even when sampled start is early")
        let afterWindow = ScheduledJourney(name:"After",plan:plan,departure:oneWindow.latestDeparture.addingTimeInterval(oneWindow.duration),speed:5)
        check(!oneWindow.overlaps(afterWindow),"Exact end of window plus route permits adjacent departure")
        let futureWindowConflict = ScheduledJourney(name:"Future",plan:plan,departure:thursday.addingTimeInterval(299),speed:5)
        check(windowed.overlaps(futureWindowConflict),"Later weekly windows participate in conflict detection")
        check(DeparturePolicy.decision(departure:tuesday.addingTimeInterval(290),now:tuesday.addingTimeInterval(301),armed:true,occupied:false,connected:true,latestDeparture:tuesday.addingTimeInterval(300)) == .missed,"Grace period cannot start route beyond window end")
        check(DeparturePolicy.decision(departure:tuesday.addingTimeInterval(290),now:tuesday.addingTimeInterval(295),armed:true,occupied:false,connected:true,latestDeparture:tuesday.addingTimeInterval(300)) == .start,"Ready route can start inside its window")
        let overnight = ScheduledJourney(name:"Overnight",plan:plan,departure:tuesday.addingTimeInterval(14*3600),speed:5,windowStart:tuesday.addingTimeInterval(14*3600),windowSeconds:7200)
        check(overnight.latestDeparture == tuesday.addingTimeInterval(16*3600),"Window can cross midnight")
        let noWindowLegacy = try! JSONDecoder().decode(ScheduledJourney.self,from:JSONSerialization.data(withJSONObject:legacy))
        check(noWindowLegacy.windowStart == nil && noWindowLegacy.windowSeconds == nil,"Old schedules decode as exact-time departures")
        print("Passed \(checks) journey checks")
    }
}
